"""
chest_slug.py — clan-name -> URL slug (короткая публичная ссылка /c/{kingdom}/{slug}).

Общая функция для chests.py (публичный /by/{kingdom}/{custom_slug}) и chest_dashboard.py
(отображение short_url в кабинете) — раньше была продублирована в обоих файлах, чинить
пришлось бы в двух местах и рано или поздно разошлись бы.

Регрессия (владелец 2026-09-25, сессия #149): клан "Феникс" (кириллица) давал ПУСТОЙ
слаг — старая _clan_to_slug вырезала regex'ом всё, кроме [a-z0-9], а кириллица ничего
из этого не содержит. "ELDORADO" (уже латиница) работал случайно. Транслитерация
переводит кириллицу в латиницу ДО фильтрации — "Феникс" -> "feniks", а не в пустоту.
"""
import re

# ГОСТ-подобная транслитерация (простой вариант, без диакритики) — покрывает русский и
# украинский алфавиты (ы/ъ/э — только русский; і/ї/є/ґ — только украинский, безвредны
# для другого языка, просто не встречаются). Реального перевода смысла НЕ делает —
# только побуквенная замена, поэтому работает для любого названия клана, не только
# для словарных слов.
_CYRILLIC_TO_LATIN = {
    'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'e',
    'ж': 'zh', 'з': 'z', 'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm',
    'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u',
    'ф': 'f', 'х': 'kh', 'ц': 'ts', 'ч': 'ch', 'ш': 'sh', 'щ': 'shch',
    'ъ': '', 'ы': 'y', 'ь': '', 'э': 'e', 'ю': 'yu', 'я': 'ya',
    'і': 'i', 'ї': 'yi', 'є': 'ye', 'ґ': 'g',
}


def transliterate(text: str) -> str:
    """Побуквенная кириллица -> латиница (нижний регистр). Всё остальное (уже латиница,
    цифры, другие алфавиты — арабский/китайский/японский и т.п.) не трогает — для них
    результат зависит от clan_to_slug ниже (при полностью нелатинском названии слаг
    получится пустым, короткая ссылка тогда не формируется, см. вызывающий код)."""
    return ''.join(_CYRILLIC_TO_LATIN.get(ch, ch) for ch in text.lower())


def clan_to_slug(clan: str) -> str:
    """Название клана -> URL-safe слаг для /c/{kingdom}/{slug}. Пустая строка, если после
    транслитерации и фильтрации ничего не осталось (например, название на языке без
    латинской транслитерации в таблице выше) — вызывающий код должен в этом случае не
    показывать короткую ссылку, а не давать /c/{kingdom}/ с пустым хвостом."""
    return re.sub(r'[^a-z0-9]+', '-', transliterate(clan)).strip('-')
